def merge_and_save():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    
    # Paths for exercises and meals
    ex_paths = [
        os.path.join(base_dir, "internal", "service", "data", "exercises.json"),
        os.path.join(base_dir, "internal", "app", "data", "exercises.json"),
    ]
    meal_paths = [
        os.path.join(base_dir, "internal", "service", "data", "meals.json"),
        os.path.join(base_dir, "internal", "app", "data", "meals.json"),
    ]

    # Load existing exercises
    with open(ex_paths[0], "r", encoding="utf-8") as f:
        existing_ex = json.load(f)
    
    existing_ex_ids = {e["id"] for e in existing_ex}
    added_ex = 0
    for e in NEW_EXERCISES:
        if e["id"] not in existing_ex_ids:
            existing_ex.append(e)
            existing_ex_ids.add(e["id"])
            added_ex += 1

    print(f"Total exercises: {len(existing_ex)} (added {added_ex})")

    for path in ex_paths:
        with open(path, "w", encoding="utf-8") as f:
            json.dump(existing_ex, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"Saved: {path}")

    # Load existing meals
    with open(meal_paths[0], "r", encoding="utf-8") as f:
        existing_meals = json.load(f)

    existing_meal_ids = {m["id"] for m in existing_meals}
    added_meals = 0
    for m in NEW_MEALS:
        if m["id"] not in existing_meal_ids:
            existing_meals.append(m)
            existing_meal_ids.add(m["id"])
            added_meals += 1

    print(f"Total meals: {len(existing_meals)} (added {added_meals})")

    for path in meal_paths:
        with open(path, "w", encoding="utf-8") as f:
            json.dump(existing_meals, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"Saved: {path}")

if __name__ == "__main__":
    merge_and_save()
