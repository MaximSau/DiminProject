package app

import (
	"fmt"
	"os"
	"strings"
)

// AIReply — ответ помощника.
// Kind честно показывает источник ответа: demo | safety | provider | error.
type AIReply struct {
	Text        string
	Kind        string
	Suggestions []string
}

// AIKey возвращает ключ провайдера из окружения.
func AIKey() string {
	for _, name := range []string{"PULSEFIT_AI_KEY", "OPENAI_API_KEY", "ANTHROPIC_API_KEY"} {
		if v := strings.TrimSpace(os.Getenv(name)); v != "" {
			return v
		}
	}
	return ""
}

// AIMode: provider — ключ есть, demo — локальный демонстрационный режим.
func AIMode() string {
	if AIKey() != "" {
		return "provider"
	}
	return "demo"
}

// AILabel — короткая подпись режима для интерфейса.
func AILabel() string {
	if AIMode() == "provider" {
		return "ИИ подключён (API)"
	}
	return "ИИ ассистент (демо-режим)"
}

// AIInfo — данные для шаблонов.
func (a *App) AIInfo() map[string]string {
	mode := AIMode()
	return map[string]string{
		"mode":  mode,
		"label": AILabel(),
		"note":  aiNote(mode),
	}
}

func aiNote(mode string) string {
	if mode == "provider" {
		return "Помощник отвечает через подключённую языковую модель. Ответы носят информационный характер и не являются медицинской консультацией."
	}
	return "Работает встроенный демонстрационный ассистент с правилами безопасности. Внешний ключ ИИ не задан, но все сценарии помощи активны."
}

